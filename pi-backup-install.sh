#!/bin/bash
# ============================================================================
#  Pi Backup installer
#  Usage: curl -fsSL https://raw.githubusercontent.com/keshavsapra/pi-backup/refs/heads/main/pi-backup-install.sh \
#           -o /tmp/pi-backup-install.sh && sudo bash /tmp/pi-backup-install.sh
#
#  What it does:
#    1. installs the pi-backup CLI to /usr/local/bin/pi-backup (from GitHub)
#    2. migrates any old v1 pi-backup scripts/cron it finds
#    3. launches `pi-backup wizard` — 7 quick questions and done
#
#  Headless (no TTY): set PI_BACKUP_BATCH=1 and config env vars:
#    PI_BACKUP_DEST=/mnt/ssd/backups  PI_BACKUP_PREFIX=pi
#    PI_BACKUP_INCLUDES=etc,home      PI_BACKUP_SCHEDULE=weekly
#    PI_BACKUP_HOUR=3                 PI_BACKUP_RETAIN_DAYS=60
# ============================================================================
set -uo pipefail

RED='\033[0;31m';  GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; BOLD='\033[1m';     NC='\033[0m'
info()    { printf "${CYAN}▸${NC} %s\n" "$*"; }
success() { printf "${GREEN}✓${NC} %s\n" "$*"; }
warn()    { printf "${YELLOW}⚠${NC} %s\n" "$*" >&2; }
die()     { printf "${RED}✗ %s${NC}\n" "$*" >&2; exit 1; }

BIN_PATH="/usr/local/bin/pi-backup"
UPSTREAM_URL="https://raw.githubusercontent.com/keshavsapra/pi-backup/main/pi-backup"

[[ $EUID -eq 0 ]] || die "Run with sudo:  sudo bash pi-backup-install.sh"

# ── a TTY is needed unless running in batch mode ────────────────────────────
if [[ ! -t 1 && "${PI_BACKUP_BATCH:-0}" != "1" ]]; then
  die "No terminal detected.
   Interactive wizard?  ssh into the Pi and run this in a normal terminal.
   Headless install?    Set PI_BACKUP_BATCH=1 plus PI_BACKUP_DEST etc.
                        (see the header comment of this script)"
fi

command -v curl >/dev/null 2>&1 || die "curl is required"

# ── splash ──────────────────────────────────────────────────────────────────
printf "${CYAN}${BOLD}\n"
printf "  🍓 Pi Backup installer — v2\n"
printf "${NC}  The one-command backup & restore wizard for Raspberry Pi\n"
printf "  %b──────────────────────────────────────────────%b\n\n" "$CYAN" "$NC"

# ============================================================================
#  1. install / update the CLI
# ============================================================================
info "Downloading the latest pi-backup CLI from GitHub…"
TMP_CLI="$(mktemp /tmp/pi-backup-cli.XXXXXX)" || die "mktemp failed"
if ! curl -fsSL "$UPSTREAM_URL" -o "$TMP_CLI"; then
  rm -f "$TMP_CLI"
  die "Could not download $UPSTREAM_URL — check your network"
fi
if ! bash -n "$TMP_CLI" 2>/dev/null; then
  rm -f "$TMP_CLI"
  die "Downloaded file failed the syntax check — refusing to install (possible tampering/network issue)"
fi
chmod 755 "$TMP_CLI"
mkdir -p "$(dirname "$BIN_PATH")"
if [[ -f "$BIN_PATH" ]] && ! mv "$TMP_CLI" "$BIN_PATH"; then
  rm -f "$TMP_CLI"
  die "Could not replace $BIN_PATH"
elif [[ ! -f "$BIN_PATH" ]] && ! mv "$TMP_CLI" "$BIN_PATH"; then
  rm -f "$TMP_CLI"
  die "Could not install $BIN_PATH"
fi
success "CLI installed: $BIN_PATH ($("$BIN_PATH" version 2>/dev/null || echo 'v?'))"

# ============================================================================
#  2. detect + migrate v1 installs
# ============================================================================
LEGACY_FOUND=0
LEGACY_PREFIX=""; LEGACY_DEST=""; LEGACY_RETAIN=""; LEGACY_INCLUDES=""

legacy_scripts() {
  shopt -s nullglob
  local f
  for f in /usr/local/bin/*-backup.sh; do
    grep -q "Auto-generated by pi-backup-install" "$f" 2>/dev/null && printf '%s\n' "$f"
  done
}

parse_legacy() {
  local f="$1"
  LEGACY_PREFIX="$(basename "$f")"; LEGACY_PREFIX="${LEGACY_PREFIX%-backup.sh}"
  LEGACY_DEST="$(grep -m1 '^DEST=' "$f" 2>/dev/null | sed 's/^DEST="\([^"]*\)"/\1/')"
  LEGACY_RETAIN="$(grep -m1 '^RETAIN=' "$f" 2>/dev/null | sed 's/^RETAIN=\([0-9]*\).*/\1/')"
  LEGACY_INCLUDES="$(grep -m1 'tar -czf "\$TAR"' "$f" 2>/dev/null \
      | sed 's/.*tar -czf "\$TAR" //; s/ 2>&1.*//')"
  LEGACY_INCLUDES="$(printf '%s' "$LEGACY_INCLUDES" | tr ' ' ',' | sed 's/,\+/,/g; s/^,//; s/,$//')"
}

legacy_cron_clear() {
  local f="$1" tmp
  tmp="$(mktemp)"
  crontab -l 2>/dev/null | grep -v -F "$f" > "$tmp" || true
  crontab "$tmp" 2>/dev/null || true
  rm -f "$tmp"
}

if mapfile -t LEGACIES < <(legacy_scripts) && (( ${#LEGACIES[@]} > 0 )); then
  parse_legacy "${LEGACIES[0]}"
  LEGACY_FOUND=1
  warn "Found an old pi-backup v1 installation:"
  printf "    script  : %s\n" "${LEGACIES[0]}"
  printf "    dest    : %s   retention: %s days\n" "${LEGACY_DEST:-?}" "${LEGACY_RETAIN:-?}"
  if [[ -t 1 ]]; then
    read -r -p "$(printf "${YELLOW}?${NC} Write these settings into the new wizard as defaults and disable the old script? [Y/n] ")" ans
    case "$ans" in
      n*|N*) LEGACY_FOUND=0 ;;
      *)
        legacy_cron_clear "${LEGACIES[0]}"
        mv "${LEGACIES[0]}" "${LEGACIES[0]}.v1-disabled"
        success "Old cron entry removed; script disabled (kept as *.v1-disabled)"
        ;;
    esac
  fi
fi

# ============================================================================
#  3. hand over to the wizard (or batch mode)
# ============================================================================
echo ""
if [[ "${PI_BACKUP_BATCH:-0}" == "1" ]]; then
  info "Batch mode: applying PI_BACKUP_* environment settings…"
  PI_BACKUP_BATCH=1 "$BIN_PATH" wizard
else
  # pass migrated v1 values to the wizard as prefills
  if [[ "$LEGACY_FOUND" == "1" ]]; then
    export PI_BACKUP_MIGRATED_DEST="$LEGACY_DEST"
    export PI_BACKUP_MIGRATED_RETAIN="$LEGACY_RETAIN"
    export PI_BACKUP_MIGRATED_INCLUDES="$LEGACY_INCLUDES"
    export PI_BACKUP_MIGRATED_PREFIX="$LEGACY_PREFIX"
  fi
  "$BIN_PATH" wizard
fi

# ============================================================================
#  done — print the cheatsheet
# ============================================================================
echo ""
success "Pi Backup is ready to go! 🍓"
echo ""
printf "  ${BOLD}Run a backup now      ${NC}  sudo pi-backup backup\n"
printf "  ${BOLD}See your backups      ${NC}  pi-backup list\n"
printf "  ${BOLD}Check health          ${NC}  sudo pi-backup doctor\n"
printf "  ${BOLD}Restore (the fun part)${NC}  sudo pi-backup restore\n"
printf "  ${BOLD}Schedule              ${NC}  systemd timer (catches up if Pi was off) or cron\n"
echo ""
printf "  One-liner sanity check:  ${CYAN}sudo pi-backup status${NC}\n\n"
